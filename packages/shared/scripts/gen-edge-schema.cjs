// Writes the edge event JSON Schema + signing vector for the Python vision service (contract tests).
const { writeFileSync, mkdirSync } = require('node:fs');
const { join } = require('node:path');
const { zodToJsonSchema } = require('zod-to-json-schema');
const { edgeEventSchema, edgeBatchSchema, EDGE_SIGNING_VECTOR } = require('../dist/edge');

const out = join(__dirname, '..', '..', '..', 'services', 'vision', 'dinesense_vision', 'contracts');
mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, 'edge-contracts.json'),
  JSON.stringify(
    {
      $comment: 'GENERATED by packages/shared/scripts/gen-edge-schema.cjs — do not edit',
      event: zodToJsonSchema(edgeEventSchema, { $refStrategy: 'none' }),
      batch: zodToJsonSchema(edgeBatchSchema, { $refStrategy: 'none' }),
      signingVector: EDGE_SIGNING_VECTOR,
    },
    null,
    2,
  ) + '\n',
);
console.log('wrote', join(out, 'edge-contracts.json'));
